"""Render results/benchmark_vol.json -> results/benchmark_vol.md (markdown tables).

Every number in the benchmark tables of README.md / MODEL_CARD.md is copied from the
file this script writes, so docs cannot drift from the scored results.
"""
from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parent.parent / "results"

FAMILY = {
    "RW": ("Naive", "Random walk (log RV_t)"), "MA22": ("Naive", "22-day mean RV"),
    "EWMA": ("Naive", "EWMA RiskMetrics λ=0.94"),
    "GARCH": ("GARCH", "GARCH(1,1)"), "GJR_GARCH": ("GARCH", "GJR-GARCH(1,1)"),
    "EGARCH": ("GARCH", "EGARCH(1,1)"),
    "HAR": ("HAR", "HAR-RV, per asset (reference)"), "HAR_pooled": ("HAR", "HAR-RV, pooled"),
    "LHAR": ("HAR", "LHAR (leverage)"), "SHAR": ("HAR", "SHAR (daily-sign semivariance)"),
    "HARX": ("HAR", "HAR-X (+VIX)"),
    "Ridge": ("ML", "Ridge"), "RandomForest": ("ML", "Random forest"), "LightGBM": ("ML", "LightGBM"),
    "TimeMixer": ("Deep", "TimeMixer"),
    "Meridian_M0": ("Meridian", "Meridian M0 (pooled HAR anchor)"),
    "Meridian_M1": ("Meridian", "Meridian M1 (per-asset HAR offset)"),
    "Meridian_M2": ("Meridian", "Meridian M2 (M1 + asset embedding)"),
    "Meridian_M3": ("Meridian", "Meridian M3 (M1 + early stopping)"),
    "Combo_HAR_LGBM": ("Combination", "GR combo: HAR + LightGBM"),
}


def label(m):
    base = m[:-4] if m.endswith("_cal") else m
    for h in ("_y_5", "_y_22"):
        if base.endswith(h):
            base = base[: -len(h)]
    if base.startswith("Combo_HAR_LGBM_Meridian_"):
        fam, name = "Combination", f"GR combo: HAR + LightGBM + {FAMILY.get(base[15:], ('', base[15:]))[1]}"
    else:
        fam, name = FAMILY.get(base, ("", base))
    return fam, name


def pct(x):
    return "—" if x is None else f"{x * 100:+.1f}%"


def fmt_p(p):
    if p is None:
        return "—"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def table(t, only_suffix=None, exclude_suffix=None, title=""):
    meta = t["_meta"]
    rows = [(k, v) for k, v in t.items() if k != "_meta"]
    if only_suffix:
        rows = [(k, v) for k, v in rows if k.endswith(only_suffix) or k.startswith("Combo")]
    if exclude_suffix:
        rows = [(k, v) for k, v in rows if not k.endswith(exclude_suffix)]
    rows.sort(key=lambda kv: kv[1]["QLIKE"])
    out = [f"**{title}** — {meta['date_range'][0]} → {meta['date_range'][1]}, "
           f"{meta['n_dates']} dates × {meta['n_assets']} assets ({meta['n_rows']} forecasts), "
           f"reference `{meta['ref']}`, HAC lag {meta['nw_lag']}.", "",
           "| Model | Family | QLIKE ↓ | vs HAR (95% CI) | DM p | RMSE log ↓ | MZ R² ↑ | IC ↑ | Hit rate | Assets beating HAR | 90% MCS |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, v in rows:
        fam, name = label(k)
        ci = v.get("ci95_pct_vs_ref")
        vs = pct(v["pct_vs_ref"]) + ("" if not ci else f" [{ci[0]*100:+.1f}, {ci[1]*100:+.1f}]")
        mcs = "✅" if v.get("in_MCS90") else ""
        out.append(f"| {name} | {fam} | {v['QLIKE']:.4f} | {vs} | {fmt_p(v['DM_p'])} | "
                   f"{v['RMSE_log']:.3f} | {v['MZ_R2']:.3f} | {v['IC']:.3f} | {v['hit_rate']*100:.1f}% | "
                   f"{v['assets_beating_ref']}/{meta['n_assets']} | {mcs} |")
    if meta.get("excluded_low_coverage"):
        out += ["", "Excluded for coverage < 98%: " +
                ", ".join(f"`{k}` ({c*100:.0f}%)" for k, c in meta["excluded_low_coverage"].items())]
    return "\n".join(out)


def main():
    R = json.loads((RESULTS / "benchmark_vol.json").read_text())
    T = R["tables"]
    parts = ["# Volatility benchmark — generated tables",
             "",
             f"Generated by `scripts/render_benchmark_md.py` from `results/benchmark_vol.json` "
             f"(inputs: {', '.join('`' + Path(p).name + '`' for p in R['inputs'])}). "
             f"Development period: dates < {R['split_date']}; holdout: dates ≥ {R['split_date']}. "
             "QLIKE is the pooled mean over asset-days; `vs HAR` is the QLIKE ratio to per-asset HAR "
             "minus 1 with a date-block bootstrap 95% CI; DM p is one-sided (model better than HAR) on "
             "the date-level loss differential with Newey–West HAC; IC is the per-asset time-series "
             "Spearman correlation averaged over assets; hit rate is the share of days where the "
             "forecast calls next-day volatility up/down vs today correctly; `_cal` models went "
             "through the same walk-forward recalibration as the reference.", ""]
    if "holdout_raw_vs_calibrated" in T:
        parts += ["## Holdout (headline): all models after the same walk-forward calibration", "",
                  table(T["holdout_raw_vs_calibrated"], only_suffix="_cal", title="Holdout, calibrated"), ""]
        parts += ["## Holdout: raw forecasts (no recalibration)", "",
                  table(T["holdout_raw"], title="Holdout, raw"), ""]
    if "holdout_vs_raw_HAR" in T:
        parts += ["## Holdout, conservative: against raw per-asset HAR (the strongest HAR form here)", "",
                  table(T["holdout_vs_raw_HAR"], title="Holdout vs raw HAR"), ""]
    if "by_year_pct_vs_raw_HAR" in R:
        by = R["by_year_pct_vs_raw_HAR"]
        ms = [m for m in ("Meridian_M0", "Combo_HAR_LGBM_Meridian_M0", "LightGBM_cal", "HAR_cal") if m in by]
        years = sorted(by[ms[0]])
        parts += ["## QLIKE vs raw per-asset HAR, by calendar year (negative = better than HAR)", "",
                  "| Year | " + " | ".join(label(m)[1] for m in ms) + " |", "|---|" + "---|" * len(ms)]
        for y in years:
            parts.append(f"| {y} | " + " | ".join(pct(by[m][str(y)] if str(y) in by[m] else by[m][y]) for m in ms) + " |")
        parts += ["", "Years better than HAR: " + ", ".join(
            f"{label(m)[1]} {sum(v < 0 for v in by[m].values())}/{len(by[m])}" for m in ms), ""]
    if "holdout_by_asset_pct_vs_raw_HAR" in R:
        ba = R["holdout_by_asset_pct_vs_raw_HAR"]
        ms = [m for m in ("Meridian_M0", "Combo_HAR_LGBM_Meridian_M0", "LightGBM_cal") if m in ba]
        parts += ["## Holdout QLIKE vs raw per-asset HAR, by asset", "",
                  "| Asset | " + " | ".join(label(m)[1] for m in ms) + " |", "|---|" + "---|" * len(ms)]
        for a in sorted(ba[ms[0]]):
            parts.append(f"| {a} | " + " | ".join(pct(ba[m][a]) for m in ms) + " |")
        parts.append("")
    if "dev_raw_vs_calibrated" in T:
        parts += ["## Development period (used for model selection)", "",
                  table(T["dev_raw_vs_calibrated"], only_suffix="_cal", title="Development, calibrated"), ""]
    for h in ("y_5", "y_22"):
        if f"holdout_{h}" in T:
            parts += [f"## Holdout, horizon {h[2:]} days (calibrated)", "", table(T[f"holdout_{h}"], title=f"h={h[2:]}"), ""]
    if "breadth_holdout" in T:
        parts += ["## Out-of-universe check: TLT, GLD (pooled models never trained on them), holdout", "",
                  table(T["breadth_holdout"], only_suffix="_cal", title="Breadth, calibrated"), ""]
    if "regimes" in R:
        regs = R["regimes"]
        models = [k for k in regs["calm"] if k != "_meta" and k.endswith("_cal")]
        models.sort(key=lambda m: regs["stress"][m]["QLIKE"])
        parts += ["## QLIKE by VIX regime (full period, calibrated)", "",
                  "| Model | Calm | Normal | Stress |", "|---|---|---|---|"]
        for m in models:
            parts.append(f"| {label(m)[1]} | " + " | ".join(
                f"{regs[r][m]['QLIKE']:.4f} ({pct(regs[r][m]['pct_vs_ref'])})" for r in ("calm", "normal", "stress")) + " |")
    (RESULTS / "benchmark_vol.md").write_text("\n".join(parts) + "\n")
    print("wrote results/benchmark_vol.md")
    if "holdout_raw_vs_calibrated" in T and "holdout_vs_raw_HAR" in T:
        block = summary_block(R)
        for doc in ("README.md", "MODEL_CARD.md"):
            inject(RESULTS.parent / doc, block)


SUMMARY_ROWS = ["Combo_HAR_LGBM_Meridian_M0", "Meridian_M0_cal", "LightGBM_cal", "HARX_cal", "Ridge_cal",
                "RandomForest_cal", "LHAR_cal", "HAR_cal", "TimeMixer_cal", "EGARCH_cal", "GJR_GARCH_cal",
                "GARCH_cal", "EWMA_cal", "RW_cal"]


def summary_block(R):
    t = R["tables"]["holdout_raw_vs_calibrated"]
    m = t["_meta"]
    s = R["tables"]["holdout_vs_raw_HAR"]
    by = R.get("by_year_pct_vs_raw_HAR", {})
    lines = [f"Holdout {m['date_range'][0]} → {m['date_range'][1]} ({m['n_dates']} trading dates × "
             f"{m['n_assets']} assets, {m['n_rows']} forecasts, never used for any modelling choice). "
             "All models get the same walk-forward recalibration; reference = per-asset HAR-RV.", "",
             "| Model | QLIKE ↓ | vs HAR (95% CI) | DM p | IC ↑ | Hit rate | Assets beating HAR |",
             "|---|---|---|---|---|---|---|"]
    for k in SUMMARY_ROWS:
        if k not in t:
            continue
        v = t[k]
        ci = v.get("ci95_pct_vs_ref")
        vs = pct(v["pct_vs_ref"]) + ("" if not ci else f" [{ci[0]*100:+.1f}, {ci[1]*100:+.1f}]")
        lines.append(f"| {label(k)[1]} | {v['QLIKE']:.4f} | {vs} | {fmt_p(v['DM_p'])} | {v['IC']:.3f} | "
                     f"{v['hit_rate']*100:.1f}% | {v['assets_beating_ref']}/{m['n_assets']} |")
    c, mm = s["Combo_HAR_LGBM_Meridian_M0"], s["Meridian_M0"]
    yrs = by.get("Meridian_M0", {})
    lines += ["", "Conservative check against the **strongest** HAR form (raw per-asset HAR, which scores "
              f"better than its calibrated version here): Meridian M0 alone {pct(mm['pct_vs_ref'])} "
              f"[{mm['ci95_pct_vs_ref'][0]*100:+.1f}, {mm['ci95_pct_vs_ref'][1]*100:+.1f}], DM p {fmt_p(mm['DM_p'])}; "
              f"combination {pct(c['pct_vs_ref'])} [{c['ci95_pct_vs_ref'][0]*100:+.1f}, "
              f"{c['ci95_pct_vs_ref'][1]*100:+.1f}], DM p {fmt_p(c['DM_p'])}; "
              f"Meridian beats HAR on {mm['assets_beating_ref']}/{s['_meta']['n_assets']} assets and in "
              f"{sum(v < 0 for v in yrs.values())}/{len(yrs)} calendar years (2012–2026). "
              "Full tables: `results/benchmark_vol.md`."]
    return "\n".join(lines)


def inject(path, block, start="<!-- BENCH:START -->", end="<!-- BENCH:END -->"):
    s = path.read_text()
    if start not in s or end not in s:
        return
    a, b = s.index(start) + len(start), s.index(end)
    path.write_text(s[:a] + "\n" + block + "\n" + s[b:])
    print(f"updated summary block in {path.name}")


if __name__ == "__main__":
    main()
